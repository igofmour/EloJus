'use strict';
const assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path'), vm = require('node:vm');
const A = require('./dist/attachment-model'), G = require('./dist/guided-model'), M = require('./dist/workspace-model'), R = require('./dist/rich-document');
const state = G.upgrade(M.createSeed()), initial = state.cases.find(c => c.guided?.type === 'initial'), defense = state.cases.find(c => c.guided?.type === 'defense');
const txt = new TextEncoder().encode('Caução fictícia de R$ 3.000,00.');
assert.equal(A.validate({name:'recibo.txt',size:txt.length},txt).mime,'text/plain');
for (const [name,size,bytes] of [['x.html',1,txt],['x.pdf',1,txt],['x.txt',0,txt],['x.txt',A.MAX_FILE+1,txt],['x.txt',1,new Uint8Array([255])]]) assert.throws(() => A.validate({name,size},bytes));
assert.equal(A.validate({name:'termo.pdf',size:8}, new TextEncoder().encode('%PDF-1.7')).ext,'pdf');
const file = {id:'file-one', name:'Caução <modelo>.txt',size:100,ext:'txt',mime:'text/plain',sha256:'sha-1',uploadedAt:new Date().toISOString()};
for (const item of [initial,defense]) A.addFile(item,file);
assert.throws(() => A.addFile(initial,{...file,id:'file-two'}),/já está/);
assert.throws(() => A.addFile(initial,{...file,id:'large',sha256:'new',size:A.MAX_CASE}),/100 MB/);
assert.equal(A.files(initial)[0].number,1);
const s = initial.sections.find(s => s.id === 'fatos');
s.delta = {ops:[{insert:s.text,attributes:{bold:true}},{insert:'\n'}]};
const link = A.addLink(initial,{id:'link-1',attachmentId:file.id,sectionId:'fatos',quote:'caução de R$ 3.000,00',location:'parágrafo 1',note:'NOTA_PRIVADA_DA_PROVA'});
A.addLink(initial,{id:'link-2',attachmentId:file.id,sectionId:'provas',location:'parágrafo 1'});
assert.throws(() => A.addLink(initial,{...link,id:'duplicate'}),/já existe/);
assert.throws(() => A.addLink(initial,{...link,id:'invalid',sectionId:'fundamentos'}),/seção/);
assert.throws(() => A.addLink(initial,{...link,id:'invalid',quote:'Texto que não consta'}),/Trecho alterado/);
assert.equal(A.issues(initial).length,0);
assert.equal(A.index(initial).split('\n').length,1,'one annex entry despite multiple links');
const projected = G.document(initial), body = projected.sections.find(s => s.id === 'fatos');
assert.ok(body.text.includes('Doc. 01 — Caução <modelo>.txt (parágrafo 1)'));
assert.ok(R.text(body).includes('Documentos relacionados:'));
assert.equal((R.text(body).match(/Documentos relacionados:/g)||[]).length,1);
assert.equal(G.document(projected),projected,'projection must be idempotent for nested exporters');
assert.ok(!JSON.stringify(projected.sections).includes('NOTA_PRIVADA_DA_PROVA'));
assert.ok(R.html(body).includes('&lt;modelo&gt;'),'filenames are escaped');
assert.ok(!s.text.includes('Documentos relacionados:'),'references never overwrite authored text');
const fp = G.fingerprint(initial); link.note += ' apenas interno'; assert.equal(G.fingerprint(initial),fp);
link.location += ' alterado'; assert.notEqual(G.fingerprint(initial),fp); link.location = 'parágrafo 1';
G.review(initial,'vinculos','checked','','marina'); assert.ok(G.requirements(initial).find(r=>r.id==='vinculos').done);
s.text = s.text.replace('caução de R$ 3.000,00','caução não especificada');
assert.match(A.linkState(initial,link),/Trecho alterado/); assert.equal(G.requirements(initial).find(r=>r.id==='vinculos').done,false);
s.text = s.text.replace('caução não especificada','caução de R$ 3.000,00');
const original = s.text; s.text += ' caução de R$ 3.000,00'; assert.match(A.linkState(initial,link),/repetido/); s.text = original;
A.files(initial)[0].archived = true; assert.match(A.linkState(initial,link),/retirado/); assert.equal(A.index(initial),'');
initial.status='review'; initial.comments=[]; assert.match(M.transition(initial,'approve','marina').message,/vínculos/);
A.files(initial)[0].archived=false; A.files(initial)[0].availability='missing'; assert.match(A.linkState(initial,link),/indisponível/);
A.files(initial)[0].availability='ready';
A.addFile(initial,{...file,id:'file-two',name:'Extra.txt',sha256:'sha-2'}); assert.equal(A.files(initial)[1].number,2);
A.files(initial)[1].archived=true;
assert.equal(A.links(defense).length,0,'links isolated per case');
const copy = G.create(initial,'ELO-900','defense'); assert.equal(A.files(copy).length,2); assert.equal(A.links(copy).length,0); assert.notEqual(A.files(copy),A.files(initial));
for (const sectionId of ['sintese','impugnacao','provas']) A.addLink(defense,{id:sectionId,attachmentId:file.id,sectionId});
assert.equal(A.issues(defense).length,0);
assert.equal(M.transition(initial,'saveVersion','marina').ok,true); assert.equal(initial.versions.at(-1).documentLinks.length,2);
assert.equal(initial.versions.at(-1).attachments.length,2);
console.log('PASS: validation, duplicates, quotas, stable numbering, case isolation, links, stale/ambiguous text, archive/restore, missing files, approval gate, projection and snapshots.');
(async()=>{

 const D=require('docx'), ZIP=require('jszip');
 const pdf=require('./dist/vendor/pdfmake.min.js'); pdf.addVirtualFileSystem(require('./dist/vendor/vfs_fonts.js'));
 const context={window:{EloGuided:G},EloRich:R,Blob};vm.runInNewContext(fs.readFileSync('dist/document-export.js','utf8'),context);
 const out=path.join(__dirname,'qa/attachments');fs.mkdirSync(out,{recursive:true});
 for(const item of [initial,defense]){
  const text=await (await context.window.EloExport.create(item,'txt','A4')).text();
  assert.ok(text.includes('Doc. 01'));assert.ok(!text.includes('NOTA_PRIVADA_DA_PROVA'));assert.ok(!text.includes('Extra.txt'));
  const docx=await D.Packer.toBuffer(R.docxDocument(item,D,'A4'));
  const xml=await (await ZIP.loadAsync(docx)).file('word/document.xml').async('string');
  assert.ok(xml.includes('Doc. 01'));assert.ok(!xml.includes('NOTA_PRIVADA_DA_PROVA'));assert.ok(!xml.includes('Extra.txt'));
  const buffer=await new Promise(resolve=>pdf.createPdf(R.pdfDefinition(item,'A4')).getBuffer(resolve));
  fs.writeFileSync(path.join(out,item.guided.type+'-vinculada.docx'),docx);
  fs.writeFileSync(path.join(out,item.guided.type+'-vinculada.pdf'),buffer);
  fs.writeFileSync(path.join(out,item.guided.type+'-vinculada.txt'),text);
 }
 console.log('PASS: DOCX XML and TXT preserve document references and exclude internal evidence notes; PDFs generated for both models.');
})().catch(e=>{console.error(e);process.exitCode=1});
