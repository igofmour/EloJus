const assert = require('node:assert/strict');
const M = require('./dist/workspace-model.js');
const now = new Date('2026-10-18T15:00:00-03:00').getTime();
const state = M.createSeed(now);
assert.equal(state.cases.length, 6);
assert.equal(new Set(state.cases.map(c => c.id)).size, 6);
assert.equal(state.cases.filter(c => c.status === 'review').length, 2);
assert.ok(M.validState(state));
const item = state.cases.find(c => c.id === 'ELO-002');
const otherCase = JSON.stringify(state.cases.find(c => c.id === 'ELO-003'));
const apply = (action, actor, data) => M.transition(item, action, actor, data, now + 1000);
assert.equal(apply('approve', 'lucas').ok, false, 'author cannot approve');
assert.equal(apply('comment', 'clara', { sectionId: 'fatos', text: 'Wrong owner' }).ok, false);
assert.equal(apply('comment', 'marina', { sectionId: 'fatos', text: 'Conferir a data do contato.', quote: '12/10', blocking: true }).ok, true);
const comment = item.comments.at(-1);
assert.equal(apply('approve', 'marina').ok, false, 'unresolved blocking comments prevent approval');
assert.equal(apply('return', 'marina').ok, true);
assert.equal(item.status, 'changes');
assert.equal(M.canEdit(item, 'lucas'), true);
assert.equal(M.canEdit(item, 'clara'), false);
const historicalText = item.versions[0].sections[1].text;
item.sections[1].text = 'A data do contato depende de confirmação documental.';
assert.equal(item.versions[0].sections[1].text, historicalText, 'versions retain immutable snapshots');
assert.equal(apply('reply', 'lucas', { commentId: comment.id, text: 'Ajustei a distinção entre relato e documento.' }).ok, true);
assert.equal(apply('address', 'lucas', { commentId: comment.id }).ok, true);
assert.equal(comment.status, 'addressed');
assert.equal(apply('submit', 'lucas').ok, true);
assert.equal(item.status, 'review');
assert.equal(apply('approve', 'marina').ok, false, 'addressed still requires reviewer resolution');
assert.equal(apply('resolve', 'lucas', { commentId: comment.id }).ok, false);
assert.equal(apply('resolve', 'marina', { commentId: comment.id }).ok, true);
assert.equal(apply('approve', 'marina').ok, true);
assert.equal(item.status, 'approved');
assert.equal(M.canEdit(item, 'marina'), false);
assert.equal(apply('saveVersion', 'marina').ok, false);
assert.equal(item.versions.at(-1).label, 'Aprovada internamente');
assert.equal(item.versions.at(-1).sections[1].text, item.sections[1].text);
assert.equal(JSON.stringify(state.cases.find(c => c.id === 'ELO-003')), otherCase, 'case state is isolated');
assert.ok(M.validState(JSON.parse(JSON.stringify(state))), 'state survives serialization');
const empty = M.createSeed(now).cases[0];
assert.equal(M.transition(empty, 'assign', 'lucas', { ownerId: 'lucas', due: '2026-10-22', instructions: 'Teste' }).ok, false);
assert.equal(M.transition(empty, 'assign', 'marina', { ownerId: 'clara', due: '2026-10-22', instructions: 'Orientações de exemplo' }).ok, true);
assert.equal(empty.status, 'working');
assert.equal(empty.ownerId, 'clara');
const legacy = { title: 'Meu caso preservado', status: 'changes', owner: 'Clara · estagiária', due: '2026-10-25', instructions: 'Orientação original', draft: 'Texto original com < > &', checks: [true, false, true], events: [{ text: 'Devolução original', at: '17/10, 10:00' }], versions: [{ text: 'Primeira versão', label: 'Rascunho', at: '17/10, 09:00' }], comments: [{ text: 'Conferir', section: 'Fatos', resolved: false }] };
const legacyBefore = JSON.stringify(legacy);
const migrated = M.importLegacy(M.createSeed(now), legacy, now).cases[0];
assert.equal(migrated.sections[0].text, legacy.draft);
assert.equal(migrated.title, legacy.title);
assert.equal(migrated.ownerId, 'clara');
assert.equal(migrated.status, 'changes');
assert.equal(migrated.versions[0].sections[0].text, 'Primeira versão');
assert.equal(migrated.events[1].legacyAt, '17/10, 10:00');
assert.equal(migrated.comments[0].sectionId, 'legado');
assert.equal(JSON.stringify(legacy), legacyBefore, 'legacy data remains unchanged');
const diff = M.diffWords('Valor pago em 08/10.', 'Valor solicitado em 08/10.');
assert.match(diff, /<del>pago /);
assert.match(diff, /<ins>solicitado /);
assert.equal(M.diffWords('<script>', '<script>'), '&lt;script&gt;');
assert.ok(!M.diffWords('antes', '<img src=x onerror=alert(1)>').includes('<img'));
assert.equal(M.validState({ schema: 2, cases: [{}] }), false);
console.log('PASS: six cases, assignment, role boundaries, review/return/address/resolve/approve, snapshots, persistence shape, case isolation, legacy preservation and safe text diffs.');
